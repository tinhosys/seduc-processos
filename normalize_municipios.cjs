function cleanKey(str) {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/['’`´\-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}


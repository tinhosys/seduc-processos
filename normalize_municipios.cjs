function normalizeMun(str) {
  if (!str || typeof str !== 'string') return str;
  const raw = str.trim();
  if (!raw) return raw;

  const k = cleanKey(raw);
  if (map.has(k)) return map.get(k);

  if (/^dist(\.|\b)/i.test(raw)) return raw;

  return raw;
}

